"""Run only the geometry section of a newly generated cloudforge-cli CAD script.

The backend creates this file in the new delivery directory. The original
script remains editable; its historic _step/export tail is never executed.
"""
import argparse
import ast
import contextlib
import importlib.util
import json
import math
from pathlib import Path
import runpy
import sys
import tempfile


def load_exporter():
    spec = importlib.util.spec_from_file_location("cloudforge_cad_preview", Path(__file__).with_name("cad-preview.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def same_ast(node, text):
    return ast.dump(node, include_attributes=False) == ast.dump(ast.parse(text).body[0], include_attributes=False)


def geometry_expr(node):
    """Allow the literal CadQuery method chains emitted by cmdCad, no file/code calls."""
    if isinstance(node, ast.Constant):
        if isinstance(node.value, float) and not math.isfinite(node.value):
            raise ValueError("生成脚本包含非有限参数")
        if not isinstance(node.value, (str, int, float, bool)):
            raise ValueError("生成脚本参数类型无效")
        return
    if isinstance(node, (ast.List, ast.Tuple)):
        for value in node.elts:
            geometry_expr(value)
        return
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)) and isinstance(node.operand, ast.Constant) and isinstance(node.operand.value, (int, float)):
        geometry_expr(node.operand)
        return
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
        func = node.func
        if isinstance(func.value, ast.Name) and func.value.id == "cq" and func.attr in ("Workplane", "Plane"):
            pass
        elif isinstance(func.value, ast.Call) and func.attr in ("polyline", "close", "extrude", "box", "circle", "sphere", "translate", "workplane", "loft"):
            geometry_expr(func.value)
        else:
            raise ValueError("生成脚本包含未允许的几何调用")
        for arg in node.args:
            geometry_expr(arg)
        for kw in node.keywords:
            if kw.arg is None or kw.arg.startswith("_"):
                raise ValueError("生成脚本包含未允许的参数")
            geometry_expr(kw.value)
        return
    raise ValueError("生成脚本包含未允许的建模表达式")


def validated_body(source):
    if not source.startswith("# Auto-generated by cloudforge-cli "):
        raise ValueError("仅允许执行本次 cloudforge-cli 新生成的建模脚本")
    tree = ast.parse(source)
    body = tree.body
    if len(body) < 9 or not same_ast(body[0], "import cadquery as cq") or not same_ast(body[1], "solids = []"):
        raise ValueError("生成脚本格式不符合 CloudForge 模板")
    # cmdCad appends this precise footer after its model assignment. Do not run
    # the footer: its _step literal can refer to another machine or old run.
    cutoff = next((i for i, node in enumerate(body) if same_ast(node, "import os")), None)
    if cutoff is None or cutoff < 3:
        raise ValueError("生成脚本缺少标准导出段")
    tail = body[cutoff:]
    if len(tail) != 7 or not isinstance(tail[1], ast.Assign) or len(tail[1].targets) != 1 or not isinstance(tail[1].targets[0], ast.Name) or tail[1].targets[0].id != "_step" or not isinstance(tail[1].value, ast.Constant) or not isinstance(tail[1].value.value, str):
        raise ValueError("生成脚本导出段不符合 CloudForge 模板")
    expected_tail = [
        "os.makedirs(os.path.dirname(_step) or '.', exist_ok=True)",
        "cq.exporters.export(model, _step)",
        "bb = (model.val() if isinstance(model, cq.Workplane) else model).BoundingBox()",
        "print('CAD model OK: solids=%d bbox=%.3f x %.3f x %.3f' % (len(solids), bb.xlen, bb.ylen, bb.zlen))",
        "print('STEP ' + ('written: ' + _step if os.path.exists(_step) else 'MISSING'))",
    ]
    if any(not same_ast(node, expected) for node, expected in zip(tail[2:], expected_tail)):
        raise ValueError("生成脚本导出段发生变化，拒绝执行")
    geometry = body[2:cutoff]
    compound = "model = cq.Compound.makeCompound([s.val() for s in solids]) if solids else cq.Workplane('XY')"
    fused = "model = shapes[0].fuse(*shapes[1:]) if len(shapes) > 1 else shapes[0]"
    if same_ast(geometry[-1], compound):
        appends = geometry[:-1]
    elif len(geometry) >= 2 and same_ast(geometry[-1], fused) and same_ast(geometry[-2], "shapes = [s.val() for s in solids]"):
        appends = geometry[:-2]
    else:
        raise ValueError("生成脚本缺少标准模型组装段")
    if not appends:
        raise ValueError("检测结果没有可导出的几何实体")
    for stmt in appends:
        if not isinstance(stmt, ast.Expr) or not isinstance(stmt.value, ast.Call):
            raise ValueError("生成脚本包含未允许的语句")
        call = stmt.value
        if not isinstance(call.func, ast.Attribute) or not isinstance(call.func.value, ast.Name) or call.func.value.id != "solids" or call.func.attr != "append" or len(call.args) != 1 or call.keywords:
            raise ValueError("生成脚本包含未允许的建模语句")
        geometry_expr(call.args[0])
    return ast.unparse(ast.Module(body=body[:cutoff], type_ignores=[])) + "\n"


def main():
    parser = argparse.ArgumentParser(description="CloudForge 新建模脚本 → 同源 STEP/STL")
    parser.add_argument("script")
    parser.add_argument("step")
    parser.add_argument("stl")
    parser.add_argument("deflection", nargs="?", type=float, default=0.005)
    parser.add_argument("--source-cloud")
    parser.add_argument("--source-span", type=float)
    args = parser.parse_args()
    exporter = load_exporter()
    try:
        script, step, stl = (Path(p).resolve() for p in (args.script, args.step, args.stl))
        if script.parent != step.parent or script.parent != stl.parent or script.suffix.lower() != ".py":
            raise ValueError("新建模脚本和 STEP/STL 必须位于同一交付目录")
        if script.stat().st_size > 2 * 1024 * 1024:
            raise ValueError("生成建模脚本过大")
        code = validated_body(script.read_text(encoding="utf-8-sig"))
        with tempfile.TemporaryDirectory(prefix=".cloudforge-model-", dir=script.parent) as temp:
            body = Path(temp) / "model.py"
            body.write_text(code, encoding="utf-8")
            with contextlib.redirect_stdout(sys.stderr):
                namespace = runpy.run_path(str(body))
                result = exporter.export_model(namespace["model"], step, stl, args.deflection,
                    route="primitive-model", source=args.source_cloud or str(script),
                    source_cloud=args.source_cloud, source_span=args.source_span)
    except Exception as exc:
        result = {"ok": False, "error": exporter.friendly_error(exc)}
    print(json.dumps(result, ensure_ascii=False, allow_nan=False))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())