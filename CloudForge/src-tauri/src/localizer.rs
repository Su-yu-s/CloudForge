/// 查中文类别名；未命中回退「类别 N」/「未知类别」
pub fn to_chinese(class_name: &str, semantic_id: i32) -> String {
    let key = class_name.trim().to_lowercase().replace('-', " ");
    // 合并连续空白为单空格（QString::simplified 语义）
    let key = key.split_whitespace().collect::<Vec<_>>().join(" ");
    for (k, v) in TABLE {
        if *k == key {
            return v.to_string();
        }
    }
    if semantic_id >= 0 {
        format!("类别 {semantic_id}")
    } else {
        "未知类别".to_string()
    }
}
